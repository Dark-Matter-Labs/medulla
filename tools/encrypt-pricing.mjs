// Encrypts the real prices for the /proposal page.
//   PROPOSAL_CODE=… node tools/encrypt-pricing.mjs [pricing.local.json]
// The code can also sit in a .proposal-code file. Both the prices file and the
// code file are git-ignored: the repo is public, so only ciphertext is committed
// (scripts/proposal-data.js). Changing the code = re-run this with a new one.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
import { createRequire } from 'node:module';

const core = createRequire(import.meta.url)('../scripts/proposal-core.js');
const src = process.argv[2] || 'pricing.local.json';
const code = (process.env.PROPOSAL_CODE || (existsSync('.proposal-code') ? readFileSync('.proposal-code', 'utf8') : '')).trim();

if (!existsSync(src)) { console.error(`No prices file at ${src}. Copy tools/pricing.example.json and fill it in.`); process.exit(1); }
if (code.length < 8) { console.error('Set PROPOSAL_CODE (or .proposal-code) to a code of at least 8 characters.'); process.exit(1); }

const pricing = JSON.parse(readFileSync(src, 'utf8'));
const payload = await core.encryptPricing(pricing, code, webcrypto);
writeFileSync('scripts/proposal-data.js',
  `// Generated by tools/encrypt-pricing.mjs from prices dated "${pricing.updated}". Do not edit.\n` +
  `window.MEDULLA_PROPOSAL_DATA = ${JSON.stringify(payload)};\n`);
console.log(`Wrote scripts/proposal-data.js (prices dated "${pricing.updated}").`);
